// Package addr defines the mesh address layout.
//
// Every endpoint (one container interface) is identified by three numbers:
//
//	node      the host it runs on             (1..65535 at most)
//	network   the private network (tenant)    (1..2^32-1)
//	endpoint  the interface within node+net   (1..65534 at most)
//
// IPv6:  fdaa:NNNN:TTTT:TTTT::EEEE      (/32 per node, /64 per node+network)
// IPv4:  10.<node><endpoint>            24 bits, split by the cluster's Layout
//
// IPv6 has room for 16 bits of each. IPv4 has 24 bits for both together, so a
// cluster chooses once how to divide them: more hosts, or more endpoints of
// one network on one host. That choice is the Layout.
//
// The IPv4 address deliberately carries no network ID: every network has the
// whole of 10.0.0.0/8 to itself, and the datapath takes the network from the
// interface a packet arrived on, never from the packet.
//
// The same layout is implemented in the eBPF datapath
// (internal/datapath/bpf/open6pn.c); change both together.
package addr

import (
	"encoding/binary"
	"fmt"
	"net/netip"
)

const (
	// Prefix is the first 16 bits of every mesh IPv6 address.
	Prefix uint16 = 0xfdaa

	// The IPv4 address has 24 bits below 10/8 for node and endpoint.
	v4Bits        = 24
	v4Base uint32 = 10 << 24

	MinNodeBits     = 8
	MaxNodeBits     = 16
	DefaultNodeBits = 14
)

var (
	// Cluster6 and Cluster4 are the ranges routed into the mesh from a container.
	Cluster6 = netip.MustParsePrefix("fdaa::/16")
	Cluster4 = netip.MustParsePrefix("10.0.0.0/8")

	// DNS is the resolver address every container uses. It lives in node 0's
	// range, so it is never routed between hosts: each host answers locally.
	DNS = netip.MustParseAddr("fdaa::53")

	// Gateway6 and Gateway4 are the next hops configured inside containers.
	// Gateway6 is assigned to the host side of every veth; Gateway4 exists
	// only as an ARP answer generated by the datapath.
	Gateway6 = netip.MustParseAddr("fe80::1")
	Gateway4 = netip.MustParseAddr("169.254.1.1")
)

// Layout is how a cluster divides the 24 bits of an IPv4 address between the
// node and the endpoint. It is fixed when the cluster is created: every
// address in the mesh depends on it.
//
//	NodeBits  hosts    endpoints per network per host
//	12         4,095   4,094
//	14        16,383   1,022
//	16        65,535     254
type Layout struct {
	NodeBits int `json:"node_bits"`
}

// DefaultLayout is used by a new cluster unless it is told otherwise.
var DefaultLayout = Layout{NodeBits: DefaultNodeBits}

// Validate reports whether the layout is one the datapath supports.
func (l Layout) Validate() error {
	if l.NodeBits < MinNodeBits || l.NodeBits > MaxNodeBits {
		return fmt.Errorf("node bits must be between %d and %d, not %d", MinNodeBits, MaxNodeBits, l.NodeBits)
	}
	return nil
}

// EndpointBits is the width of the endpoint field in an IPv4 address.
func (l Layout) EndpointBits() int { return v4Bits - l.NodeBits }

// MaxNode is the highest node ID. Node 0 is reserved for infrastructure
// addresses.
func (l Layout) MaxNode() uint16 { return uint16(1<<l.NodeBits - 1) }

// MaxEndpoint is the highest endpoint ID. Zero and all-ones are reserved.
func (l Layout) MaxEndpoint() uint16 { return uint16(1<<l.EndpointBits() - 2) }

// ValidNode reports whether id can be assigned to a host.
func (l Layout) ValidNode(id uint16) bool { return id >= 1 && id <= l.MaxNode() }

// ValidEndpoint reports whether id can be assigned to an endpoint.
func (l Layout) ValidEndpoint(id uint16) bool { return id >= 1 && id <= l.MaxEndpoint() }

// V4 returns the IPv4 address of an endpoint.
func (l Layout) V4(node, endpoint uint16) netip.Addr {
	var b [4]byte
	binary.BigEndian.PutUint32(b[:], v4Base|uint32(node)<<l.EndpointBits()|uint32(endpoint))
	return netip.AddrFrom4(b)
}

func (l Layout) String() string {
	return fmt.Sprintf("%d node bits: up to %d hosts, %d endpoints per network per host", l.NodeBits, l.MaxNode(), l.MaxEndpoint())
}

// V6 returns the IPv6 address of an endpoint.
func V6(node uint16, network uint32, endpoint uint16) netip.Addr {
	var b [16]byte
	binary.BigEndian.PutUint16(b[0:], Prefix)
	binary.BigEndian.PutUint16(b[2:], node)
	binary.BigEndian.PutUint32(b[4:], network)
	binary.BigEndian.PutUint16(b[14:], endpoint)
	return netip.AddrFrom16(b)
}

// NodePrefix returns the IPv6 range owned by a node. It is the node's
// WireGuard AllowedIPs entry, which makes it the route as well.
func NodePrefix(node uint16) netip.Prefix {
	return netip.PrefixFrom(V6(node, 0, 0), 32)
}

// Parse6 splits a mesh IPv6 address into its parts.
func Parse6(a netip.Addr) (node uint16, network uint32, endpoint uint16, err error) {
	if !a.Is6() || a.Is4In6() {
		return 0, 0, 0, fmt.Errorf("%s is not a mesh IPv6 address", a)
	}
	b := a.As16()
	if binary.BigEndian.Uint16(b[0:]) != Prefix {
		return 0, 0, 0, fmt.Errorf("%s is outside %s", a, Cluster6)
	}
	for _, x := range b[8:14] {
		if x != 0 {
			return 0, 0, 0, fmt.Errorf("%s has a non-zero reserved field", a)
		}
	}
	node = binary.BigEndian.Uint16(b[2:])
	network = binary.BigEndian.Uint32(b[4:])
	endpoint = binary.BigEndian.Uint16(b[14:])
	return node, network, endpoint, nil
}
